//! `jax.lock`: the exact, hashed result of dependency resolution.

use std::collections::BTreeMap;

use crate::toml::{self, Value};
use crate::version::Version;

#[derive(Debug, Clone, PartialEq)]
pub struct LockedPackage {
    pub version: Version,
    /// Registry name, `path:<dir>` or `git:<url>#<rev>`.
    pub source: String,
    /// SHA-256 of the package contents (hex). Empty for path dependencies.
    pub sha256: String,
    pub deps: Vec<String>,
}

#[derive(Debug, Clone, PartialEq)]
pub struct Lockfile {
    pub format: i64,
    /// The exact toolchain the lock was produced with.
    pub jax: Version,
    pub packages: BTreeMap<String, LockedPackage>,
}

impl Lockfile {
    pub fn new(jax: Version) -> Lockfile {
        Lockfile {
            format: 1,
            jax,
            packages: BTreeMap::new(),
        }
    }

    pub fn parse(src: &str) -> Result<Lockfile, String> {
        let root = toml::parse(src).map_err(|e| e.to_string())?;
        let format = match root.get("format") {
            Some(Value::Int(n)) => *n,
            _ => return Err("jax.lock: missing `format`".into()),
        };
        if format != 1 {
            return Err(format!("jax.lock: unsupported lockfile format {format}"));
        }
        let jax = match root.get("jax") {
            Some(Value::Str(s)) => Version::parse(s).map_err(|e| format!("jax.lock: `jax`: {e}"))?,
            _ => return Err("jax.lock: missing `jax`".into()),
        };
        let mut packages = BTreeMap::new();
        if let Some(Value::Table(pkgs)) = root.get("package") {
            for (name, v) in pkgs {
                let Value::Table(t) = v else {
                    return Err(format!("jax.lock: package `{name}` must be a table"));
                };
                let get = |k: &str| -> Result<String, String> {
                    match t.get(k) {
                        Some(Value::Str(s)) => Ok(s.clone()),
                        _ => Err(format!("jax.lock: package `{name}` is missing `{k}`")),
                    }
                };
                let version = Version::parse(&get("version")?).map_err(|e| format!("jax.lock: `{name}`: {e}"))?;
                let deps = match t.get("deps") {
                    Some(Value::Array(a)) => a
                        .iter()
                        .filter_map(|v| if let Value::Str(s) = v { Some(s.clone()) } else { None })
                        .collect(),
                    _ => Vec::new(),
                };
                packages.insert(
                    name.clone(),
                    LockedPackage {
                        version,
                        source: get("source")?,
                        sha256: t.get("sha256").and_then(|v| if let Value::Str(s) = v { Some(s.clone()) } else { None }).unwrap_or_default(),
                        deps,
                    },
                );
            }
        }
        Ok(Lockfile {
            format,
            jax,
            packages,
        })
    }

    /// Deterministic serialization (sorted keys, stable layout).
    pub fn to_toml(&self) -> String {
        let mut out = String::from("# This file is generated by Jax. Do not edit by hand.\n");
        out.push_str(&format!("format = {}\n", self.format));
        out.push_str(&format!("jax = {}\n", toml::quote(&self.jax.to_string())));
        for (name, p) in &self.packages {
            out.push_str(&format!("\n[package.{}]\n", toml::key(name)));
            out.push_str(&format!("version = {}\n", toml::quote(&p.version.to_string())));
            out.push_str(&format!("source = {}\n", toml::quote(&p.source)));
            if !p.sha256.is_empty() {
                out.push_str(&format!("sha256 = {}\n", toml::quote(&p.sha256)));
            }
            if !p.deps.is_empty() {
                let deps: Vec<String> = p.deps.iter().map(|d| toml::quote(d)).collect();
                out.push_str(&format!("deps = [{}]\n", deps.join(", ")));
            }
        }
        out
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn roundtrip() {
        let mut l = Lockfile::new(Version::new(0, 1, 0));
        l.packages.insert(
            "acme.chart".into(),
            LockedPackage {
                version: Version::new(2, 1, 0),
                source: "hub".into(),
                sha256: "ab".repeat(32),
                deps: vec!["acme.core".into()],
            },
        );
        let text = l.to_toml();
        assert_eq!(Lockfile::parse(&text).unwrap(), l);
        assert_eq!(text, l.to_toml());
    }
}
